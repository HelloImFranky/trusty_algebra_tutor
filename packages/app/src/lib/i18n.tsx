export type Locale = 'en' | 'es';
export type I18nKey = keyof (typeof dict)['en'];

const I18nContext = createContext<{
  locale: Locale;
  t: (k: I18nKey) => string;
  setLocale: (l: Locale) => void;
}>({ locale: 'en', t: (k) => dict.en[k], setLocale: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en');

  useEffect(() => {
    void (async () => {
      const saved = (await storage.get('tutor.locale')) as Locale | null;
      setLocaleState(saved ?? getAuth()?.user.locale ?? 'en');
    })();
  }, []);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    void storage.set('tutor.locale', l);
    if (getAuth()) client.auth.setLocale.mutate({ locale: l }).catch(() => {});
  };
  return (
    <I18nContext.Provider value={{ locale, t: (k) => dict[locale][k], setLocale }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
