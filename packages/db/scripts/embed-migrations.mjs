// Embed migrations/*.sql into src/migrationsData.ts so the runner works in
// bundled runtimes (Next.js standalone) where the .sql files aren't on disk.
// Runs automatically via the package's `generate` script; the .sql files
// remain the source of truth.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const root = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'migrations');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((name) => ({
  name,
  sql: fs.readFileSync(path.join(dir, name), 'utf8'),
}));

const out =
  '// GENERATED by scripts/embed-migrations.mjs — do not edit; edit migrations/*.sql\n' +
  'export const migrations: { name: string; sql: string }[] = ' +
  JSON.stringify(entries, null, 2) +
  ';\n';
fs.writeFileSync(path.join(root, 'src/migrationsData.ts'), out);
console.log(`embedded ${files.length} migrations`);
